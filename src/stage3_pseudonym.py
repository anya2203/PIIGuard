"""Stage 3: Pseudonymization and Span Management Engine.

Module: stage3_pseudonym
Part of the PIIGuard Offline PII Detection and Pseudonymization Pipeline.

CRITICAL DISCLAIMER:
    Synthetic surrogate values generated by this module (such as simulated names,
    phone numbers, Aadhaar IDs, and PANs) are produced for privacy-preserving NLP
    benchmarking and testing. They are NOT guaranteed to be unassigned, active,
    or valid real-world identifiers. No claim of real-world authenticity or
    official issuance is made.

SECURITY & PRIVACY NOTICE:
    This module operates 100% offline in local memory. It never communicates with
    any remote API, cloud service, telemetry, or external network endpoint.
    Text outside identified spans is strictly preserved byte-for-byte.
"""

from __future__ import annotations

import logging
import random
import re
from typing import Any, Final

from faker import Faker

# Configure quiet logger (never log raw PII text)
logger = logging.getLogger(__name__)

# Canonical labels (mirrored from stage1_regex for standalone flexibility)
LABEL_EMAIL: Final[str] = "EMAIL"
LABEL_PHONE: Final[str] = "PHONE"
LABEL_AADHAAR: Final[str] = "AADHAAR"
LABEL_PAN: Final[str] = "PAN"
LABEL_IP_ADDRESS: Final[str] = "IP_ADDRESS"


class Pseudonymizer:
    """Manages consistent entity surrogate generation and right-to-left span replacement."""

    def __init__(self, seed: int | None = None, locale: str = "en_IN") -> None:
        """Initialize the Pseudonymizer with Faker instance and empty mapping vaults.

        Args:
            seed: Optional integer seed for reproducible synthetic generation in tests.
            locale: Faker locale (defaults to 'en_IN' for Indian context).
        """
        try:
            self.fake = Faker(locale)
        except Exception:
            # Fallback to default locale if requested locale is unavailable
            self.fake = Faker()

        if seed is not None:
            Faker.seed(seed)
            random.seed(seed)

        # Mapping dictionaries:
        # mapping: key is f"{entity_type}:{normalized_original_value}" -> surrogate string
        # reverse_mapping: key is surrogate string -> original raw value (for local deanonymization)
        self._mapping: dict[str, str] = {}
        self._reverse_mapping: dict[str, str] = {}

    @property
    def mapping(self) -> dict[str, str]:
        """Return a copy of the entity mapping table."""
        return dict(self._mapping)

    @property
    def reverse_mapping(self) -> dict[str, str]:
        """Return a copy of the reverse surrogate lookup table."""
        return dict(self._reverse_mapping)

    def clear(self) -> None:
        """Reset internal mappings."""
        self._mapping.clear()
        self._reverse_mapping.clear()

    @staticmethod
    def normalize_value(label: str, raw_text: str) -> str:
        """Normalize original entity text according to its semantic entity type.

        This ensures that variations like '+91 98765 43210' and '98765-43210',
        or lowercase vs uppercase PANs, map to the same surrogate identifier.

        Args:
            label: Entity type (e.g. 'EMAIL', 'PHONE', 'AADHAAR', 'PAN', 'IP_ADDRESS').
            raw_text: Raw string matched from the source text.

        Returns:
            Normalized canonical string.
        """
        text = raw_text.strip()
        canonical_label = label.upper()

        if canonical_label == LABEL_EMAIL:
            # Email addresses are case-insensitive
            return text.lower()

        elif canonical_label == LABEL_PAN:
            # PAN numbers are case-insensitive alphanumeric
            return text.upper()

        elif canonical_label == LABEL_PHONE:
            # Strip whitespace and hyphens
            digits = re.sub(r"[\s-]", "", text)
            # Remove leading country codes or trunk prefixes
            if digits.startswith("+91"):
                digits = digits[3:]
            elif digits.startswith("91") and len(digits) == 12:
                digits = digits[2:]
            elif digits.startswith("0") and len(digits) == 11:
                digits = digits[1:]
            return digits

        elif canonical_label == LABEL_AADHAAR:
            # Strip whitespace and hyphens to get raw 12 digits
            return re.sub(r"[\s-]", "", text)

        elif canonical_label == LABEL_IP_ADDRESS:
            # Normalize whitespace
            return text.strip()

        return text

    def get_or_create_surrogate(self, label: str, raw_text: str) -> str:
        """Retrieve existing surrogate for an entity or generate and register a new one.

        Uses entity type plus normalized original value as the mapping key.

        Args:
            label: Entity type label.
            raw_text: Original raw text of the entity.

        Returns:
            Synthetic surrogate string.
        """
        canonical_label = label.upper()
        normalized = self.normalize_value(canonical_label, raw_text)
        mapping_key = f"{canonical_label}:{normalized}"

        if mapping_key in self._mapping:
            return self._mapping[mapping_key]

        # Generate a new synthetic surrogate according to entity type
        surrogate = self._generate_surrogate(canonical_label, raw_text)

        # Store in mapping
        self._mapping[mapping_key] = surrogate
        self._reverse_mapping[surrogate] = raw_text

        return surrogate

    def _generate_surrogate(self, label: str, raw_text: str) -> str:
        """Generate a realistic yet synthetic surrogate for a specific entity type."""
        canonical_label = label.upper()

        if canonical_label == LABEL_EMAIL:
            # Generate synthetic email
            user_part = self.fake.user_name()
            domain = self.fake.free_email_domain()
            return f"{user_part}@{domain}"

        elif canonical_label == LABEL_PHONE:
            # Generate synthetic 10-digit Indian mobile number
            prefix_choice = self.fake.random_element(["98", "99", "97", "96", "88", "87", "70", "63"])
            remaining_digits = "".join(str(random.randint(0, 9)) for _ in range(8))
            ten_digits = f"{prefix_choice}{remaining_digits}"

            # Preserve formatting style of raw input if applicable
            has_plus91 = raw_text.strip().startswith("+91")
            has_space_group = " " in raw_text.strip()
            has_hyphen_group = "-" in raw_text.strip()

            if has_plus91:
                if has_space_group:
                    return f"+91 {ten_digits[:5]} {ten_digits[5:]}"
                elif has_hyphen_group:
                    return f"+91-{ten_digits[:5]}-{ten_digits[5:]}"
                return f"+91 {ten_digits}"
            elif has_space_group:
                return f"{ten_digits[:5]} {ten_digits[5:]}"
            elif has_hyphen_group:
                return f"{ten_digits[:5]}-{ten_digits[5:]}"
            return ten_digits

        elif canonical_label == LABEL_AADHAAR:
            # Generate synthetic 12-digit Aadhaar surrogate
            try:
                raw_aadhaar = str(self.fake.aadhaar_id())
            except Exception:
                raw_aadhaar = "".join(str(random.randint(0, 9)) for _ in range(12))

            # Ensure 12 digits
            raw_aadhaar = (raw_aadhaar + "000000000000")[:12]

            # Preserve format (spaces or hyphens)
            if " " in raw_text:
                return f"{raw_aadhaar[:4]} {raw_aadhaar[4:8]} {raw_aadhaar[8:]}"
            elif "-" in raw_text:
                return f"{raw_aadhaar[:4]}-{raw_aadhaar[4:8]}-{raw_aadhaar[8:]}"
            return raw_aadhaar

        elif canonical_label == LABEL_PAN:
            # Generate synthetic 10-character PAN surrogate
            try:
                pan_val = str(self.fake.pan())
            except Exception:
                letters = "".join(random.choices("ABCDEFGHIJKLMNOPQRSTUVWXYZ", k=5))
                digits = "".join(random.choices("0123456789", k=4))
                last_letter = random.choice("ABCDEFGHIJKLMNOPQRSTUVWXYZ")
                pan_val = f"{letters}{digits}{last_letter}"

            # Match case of original text
            if raw_text.islower():
                return pan_val.lower()
            return pan_val.upper()

        elif canonical_label == LABEL_IP_ADDRESS:
            # Generate synthetic IPv4 address
            return str(self.fake.ipv4())

        # Generic fallback
        return f"[SYNTHETIC_{canonical_label}]"

    def pseudonymize(
        self,
        text: str,
        entities: list[dict[str, Any]],
    ) -> str:
        """Pseudonymize input text by replacing detected entity spans right-to-left.

        Features:
        - Detects and safely skips invalid or out-of-bounds spans.
        - Detects and skips overlapping spans.
        - Replaces spans from right to left so remaining offsets are never corrupted.
        - Preserves all surrounding characters without alteration.

        Args:
            text: Original raw input string.
            entities: List of entity dictionaries with 'start', 'end', and 'label'.

        Returns:
            The pseudonymized string with surrogates in place of original PII.
        """
        if not text or not entities:
            return text

        # Step 1: Filter and validate span bounds
        valid_spans: list[dict[str, Any]] = []
        text_len = len(text)

        for span in entities:
            start = span.get("start")
            end = span.get("end")
            label = span.get("label")

            # Must have valid integer bounds and a label
            if not isinstance(start, int) or not isinstance(end, int) or not label:
                continue

            # Bounds must be non-negative, start < end, and within text length
            if start < 0 or start >= end or end > text_len:
                continue

            # Check if span text matches slice if provided
            expected_text = span.get("text")
            if expected_text is not None and text[start:end] != expected_text:
                # Text mismatch indicating stale offsets; skip safely
                continue

            valid_spans.append(span)

        if not valid_spans:
            return text

        # Step 2: Detect and filter out overlapping spans
        # Sort candidate spans by start offset ascending, then by span length descending.
        # This prioritizes longer spans when starting at the same position.
        sorted_candidates = sorted(
            valid_spans,
            key=lambda s: (s["start"], -(s["end"] - s["start"])),
        )

        non_overlapping: list[dict[str, Any]] = []
        last_end = -1

        for span in sorted_candidates:
            if span["start"] >= last_end:
                non_overlapping.append(span)
                last_end = span["end"]
            else:
                # Overlap detected: safely skip the conflicting span
                continue

        # Step 3: Replace spans from right to left (descending order of start offset).
        # This guarantees that offset modifications never affect subsequent replacements!
        spans_right_to_left = sorted(
            non_overlapping,
            key=lambda s: s["start"],
            reverse=True,
        )

        result_text = text
        for span in spans_right_to_left:
            start = span["start"]
            end = span["end"]
            label = span["label"]
            original_span_text = text[start:end]

            surrogate = self.get_or_create_surrogate(label, original_span_text)

            # Splice surrogate into string preserving left and right boundaries
            result_text = result_text[:start] + surrogate + result_text[end:]

        return result_text

